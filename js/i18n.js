let CURRENT_LANG = "ru";

function setLanguage(lang) {
  CURRENT_LANG = TRANSLATIONS[lang] ? lang : "ru";
  document.documentElement.setAttribute("lang", CURRENT_LANG);
}

function t(key) {
  const dict = TRANSLATIONS[CURRENT_LANG] || TRANSLATIONS.ru;
  return dict[key] != null ? dict[key] : (TRANSLATIONS.ru[key] != null ? TRANSLATIONS.ru[key] : key);
}

function applyStaticTranslations(root) {
  (root || document).querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  (root || document).querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  (root || document).querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  (root || document).querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
}
